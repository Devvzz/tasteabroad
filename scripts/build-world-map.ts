// Writes lib/world-path.ts: the land outline as one SVG path, so the taste map needs no map library in the browser.
// Run: npm run build:map   (only needed again to change the map's detail or projection)
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { geoEquirectangular, geoPath } from "d3-geo";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";
import land from "world-atlas/land-110m.json";
import { MAP_WIDTH } from "../lib/world-map";

const topology = land as unknown as Topology<{ land: GeometryCollection }>;
// Same projection as project() in lib/world-map.ts: longitude -180..180 maps to 0..MAP_WIDTH.
const projection = geoEquirectangular().scale(MAP_WIDTH / (2 * Math.PI)).translate([MAP_WIDTH / 2, MAP_WIDTH / 4]).precision(0.5);
const path = geoPath(projection).digits(1)(feature(topology, topology.objects.land)) ?? "";

const out = join(__dirname, "..", "lib", "world-path.ts");
writeFileSync(out, `// Generated by scripts/build-world-map.ts from Natural Earth (world-atlas land-110m). Do not edit.\nexport const WORLD_PATH =\n  ${JSON.stringify(path)};\n`);
console.log(`wrote ${out} (${(path.length / 1024).toFixed(1)} KB)`);
